import fs from "node:fs";
import path from "node:path";

const root=process.cwd();
const output=path.join(root,"src/generated/forgeProjectRegistry.ts");

const projectEntries=[
  {slug:"active",projectPath:"config/studio-project.json",active:true},
  ...fs.existsSync(path.join(root,"clients"))
    ? fs.readdirSync(path.join(root,"clients"),{withFileTypes:true})
        .filter((entry)=>entry.isDirectory() && fs.existsSync(path.join(root,"clients",entry.name,"studio-project.json")))
        .map((entry)=>({slug:entry.name,projectPath:`clients/${entry.name}/studio-project.json`,active:false}))
    : [],
];

const imports=[];
const records=[];
let importIndex=0;

for(const entry of projectEntries) {
  const project=readJson(entry.projectPath);
  const projectImport=addImport(entry.projectPath,"project");
  const experienceImport=addImport(project.experiencePath,"experience");

  const baseDir=path.posix.dirname(entry.projectPath);
  const experienceDir=path.posix.dirname(project.experiencePath);
  const assetPath=firstExisting([
    path.posix.join(experienceDir,"asset-manifest.json"),
    path.posix.join(baseDir,"asset-manifest.json"),
    entry.active ? "config/asset-manifest.json" : "",
  ]);
  const cinematicPath=firstExisting([
    path.posix.join(experienceDir,"cinematic-systems.json"),
    path.posix.join(baseDir,"cinematic-systems.json"),
    entry.active ? "config/cinematic-systems.json" : "",
  ]);
  const graphPath=firstExisting([
    path.posix.join(baseDir,"interaction-graph.json"),
    entry.active ? "config/interaction-graph.json" : "",
  ]);
  const assetImport=assetPath ? addImport(assetPath,"assetManifest") : "null";
  const cinematicImport=cinematicPath ? addImport(cinematicPath,"cinematicSystems") : "null";
  const graphImport=graphPath ? addImport(graphPath,"interactionGraph") : "null";
  const liveHref=entry.active ? "/site" : fs.existsSync(path.join(root,"app",entry.slug,"page.tsx")) ? `/${entry.slug}` : null;

  records.push(`  {
    slug:${JSON.stringify(entry.slug)},
    active:${entry.active},
    liveHref:${JSON.stringify(liveHref)},
    project:${projectImport},
    experience:${experienceImport},
    assetManifest:${assetImport},
    cinematicSystems:${cinematicImport},
    interactionGraph:${graphImport},
  }`);
}

const source=`// AUTO-GENERATED by scripts/generate-forge-project-registry.mjs.
// Do not hand-edit. This file gives Next/Turbopack a static import graph for every Forge project.
${imports.join("\n")}

export const forgeProjectRegistry=[
${records.join(",\n")}
] as const;
`;

fs.mkdirSync(path.dirname(output),{recursive:true});
fs.writeFileSync(output,source);
console.log(`Generated ${path.relative(root,output)} with ${projectEntries.length} Forge project(s).`);

function addImport(relativePath,prefix) {
  const normalized=normalizeProjectPath(relativePath);
  const name=`${prefix}${importIndex++}`;
  imports.push(`import ${name} from ${JSON.stringify("@/"+normalized)};`);
  return name;
}

function normalizeProjectPath(value) {
  if(typeof value!=="string" || !value.endsWith(".json")) throw new Error(`Forge registry path must be a JSON file: ${value}`);
  const normalized=value.replace(/\\/g,"/").replace(/^\.\//,"");
  const absolute=path.resolve(root,normalized);
  const relative=path.relative(root,absolute);
  if(relative.startsWith("..") || path.isAbsolute(relative)) throw new Error(`Forge registry path escapes repository root: ${value}`);
  if(!fs.existsSync(absolute) || !fs.statSync(absolute).isFile()) throw new Error(`Forge registry source is missing: ${normalized}`);
  return normalized;
}

function firstExisting(candidates) {
  for(const candidate of candidates.filter(Boolean)) {
    const normalized=candidate.replace(/\\/g,"/");
    const absolute=path.resolve(root,normalized);
    const relative=path.relative(root,absolute);
    if(relative.startsWith("..") || path.isAbsolute(relative)) continue;
    if(fs.existsSync(absolute) && fs.statSync(absolute).isFile()) return normalized;
  }
  return null;
}

function readJson(relativePath) {
  const normalized=normalizeProjectPath(relativePath);
  return JSON.parse(fs.readFileSync(path.join(root,normalized),"utf8"));
}
